for team, data in pairs(landmarks) do
    local function add(kind, pos, lane, tier)
        Map[#Map + 1] = {
            kind = kind, mapTeam = team, lane = lane, tier = tier,
            pos = Vector(pos[1], pos[2], pos[3]),
        }
    end
    add("fountain", data.fountain)
    add("ancient", data.ancient)
    for lane, pos in pairs(data.start) do add("lane", pos, lane) end
    for lane, towers in pairs(data.towers) do
        for tier, pos in ipairs(towers) do add("tower", pos, lane, tier) end
    end
    for lane, camps in pairs(data.camps) do
        for _, pos in ipairs(camps) do add("camp", pos, lane) end
    end
    for _, pos in ipairs(data.wards) do add("ward_spot", pos) end
end

return Map
